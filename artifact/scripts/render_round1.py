def policy():
    rows = rd("e2_policy.csv")
    if not rows:
        return
    R = {(r["gap"], r["phase"], r["policy"]): r for r in rows}
    lines = []
    pols = ["ev", "te", "trig", "lme", "lm", "gl"]
    for phase in ("early", "late"):
        lines.append("\\addlinespace[2pt]\\multicolumn{8}{@{}l}{\\emph{%s decision (+%s\\,s after the gap ends)}}\\\\" % ("Early" if phase == "early" else "Late", "2" if phase == "early" else "14"))
        for g in GAPS:
            if (g, phase, "ev") not in R:
                continue
            cells = []
            for p in pols:
                r = R[(g, phase, p)]
                cells.append(pct(r["miss_rate"], 0))
            lines.append("%s & %s & %s \\\\" % (GAPNAME[g], R[(g, phase, "ev")]["changed"], " & ".join(cells)))
    wr("tab_policy.tex", r"""\begin{table*}[t]
\centering
\caption{Missed changes (E2): \% of changed facts that each policy used without refreshing, i.e., stale critical decisions. ``Changed'' counts changed fact uses (16 base + 3 derived facts per trial). Wilson 95\% intervals for the late decision are in Figure~\ref{fig:miss}.}
\label{tab:policy}
\footnotesize
\begin{tabular}{@{}lrrrrrrr@{}}
\toprule
Gap & Changed & """ + " & ".join(POLNAME[p] for p in pols) + r""" \\
\midrule
""" + "\n".join(lines) + r"""
\bottomrule
\end{tabular}
\end{table*}
""")
    # bar figure (late)
    colors = {"ev": "red!65", "trig": "orange!80", "lme": "violet!55", "lm": "green!55!black"}
    plots = []
    gaps = [g for g in GAPS if (g, "late", "ev") in R]
    for p in ["ev", "trig", "lme", "lm"]:
        coords = []
        for g in gaps:
            r = R[(g, "late", p)]
            m = 100 * float(r["miss_rate"])
            lo, hi = 100 * float(r["miss_lo"]), 100 * float(r["miss_hi"])
            coords.append("(%s,%.2f) +- (0,%.2f) -= (0,%.2f)" % (GAPSHORT[g], m, hi - m, m - lo))
        plots.append("\\addplot+[fill=%s,draw=black!60,error bars/.cd,y dir=both,y explicit] coordinates {%s};" % (colors[p], " ".join(coords)))
    xt = ",".join(GAPSHORT[g] for g in gaps)
    wr("fig_miss.tex", r"""\begin{figure}[t]
\centering
\begin{tikzpicture}
\begin{axis}[ybar, bar width=3.2pt, width=\columnwidth, height=4.6cm, ymin=0, ymax=105,
  symbolic x coords={""" + xt + r"""}, xtick=data, xticklabel style={font=\scriptsize},
  ylabel={Missed changes (\%)}, ylabel style={font=\small}, yticklabel style={font=\scriptsize},
  legend style={font=\scriptsize, at={(0.5,1.03)}, anchor=south, legend columns=4, draw=none},
  enlarge x limits=0.08, error bars/error bar style={black!70}]
""" + "\n".join(plots) + r"""
\legend{Event-only, +OS trigger, \sys-epoch, \sys}
\end{axis}
\end{tikzpicture}
\caption{Missed changes at the late decision (+14\,s), with Wilson 95\% intervals. \sys misses none. Tether-style, which refines event-only, misses at least as many (Table~\ref{tab:policy}).}
\label{fig:miss}
\end{figure}
""")
    # macros: per gap/policy/phase
    for (g, ph, p), r in R.items():
        key = "Miss%s%s%s" % (g.capitalize(), ph.capitalize(), {"ev": "Ev", "te": "Te", "trig": "Trig", "lme": "Lme", "lm": "Lm", "gl": "Gl"}[p])
        mac(key, pct(r["miss_rate"], 0) + "\\%")
        if p in ("lm", "ev", "gl", "te", "lme", "trig") and ph == "late":
            mac("Ref" + g.capitalize() + {"ev": "Ev", "te": "Te", "trig": "Trig", "lme": "Lme", "lm": "Lm", "gl": "Gl"}[p], pct(r["refresh_rate"], 0) + "\\%")
            mac("Unnec" + g.capitalize() + {"ev": "Ev", "te": "Te", "trig": "Trig", "lme": "Lme", "lm": "Lm", "gl": "Gl"}[p], pct(r["unnec_rate"], 0) + "\\%")


# ------------------------------------------------------------------ TTL line plot
def ttl():
    rows = rd("e2_ttl.csv")
    pol = rd("e2_policy.csv")
    if not rows or not pol:
        return
    # pooled over all gaps, late decision: refresh rate (x) vs missed-change rate (y)
    agg = {}
    for r in rows:
        if r["phase"] != "late":
            continue
        t = int(r["ttl_s"])
        a = agg.setdefault(t, [0, 0, 0.0, 0])
        a[0] += int(r["missed"]); a[1] += int(r["changed"])
    uses = {}
    for r in pol:
        if r["phase"] == "late" and r["policy"] == "gl":
            uses[r["gap"]] = int(r["uses"])
    for r in rows:
        if r["phase"] == "late":
            agg[int(r["ttl_s"])][2] += float(r["refresh_rate"]) * uses.get(r["gap"], 0)
            agg[int(r["ttl_s"])][3] += uses.get(r["gap"], 0)
    ttl_pts = " ".join("(%.2f,%.2f)" % (100 * a[2] / max(1, a[3]), 100 * a[0] / max(1, a[1])) for t, a in sorted(agg.items()))
    P = {}
    for r in pol:
        if r["phase"] != "late":
            continue
        a = P.setdefault(r["policy"], [0, 0, 0, 0])
        a[0] += int(r["missed"]); a[1] += int(r["changed"]); a[2] += int(r["refresh"]); a[3] += int(r["uses"])
    marks = {"ev": ("red", "triangle*", "Event-only"), "te": ("red!50!black", "diamond*", "Tether-style"),
             "trig": ("orange!85!black", "square*", "+OS trigger"), "lme": ("violet", "pentagon*", "\\sys-epoch"),
             "lm": ("green!50!black", "*", "\\sys"), "gl": ("blue", "o", "Global")}
    pts = []
    for p in ["ev", "te", "trig", "lme", "lm", "gl"]:
        a = P[p]
        c, m, nm = marks[p]
        pts.append("\\addplot[only marks,mark=%s,mark size=2.4pt,color=%s] coordinates {(%.2f,%.2f)};\n\\addlegendentry{%s}" % (m, c, 100 * a[2] / a[3], 100 * a[0] / a[1], nm))
        mac("Pool" + {"ev": "Ev", "te": "Te", "trig": "Trig", "lme": "Lme", "lm": "Lm", "gl": "Gl"}[p] + "Ref", pct(a[2] / a[3], 0) + "\\%")
        mac("Pool" + {"ev": "Ev", "te": "Te", "trig": "Trig", "lme": "Lme", "lm": "Lm", "gl": "Gl"}[p] + "Miss", pct(a[0] / a[1], 0) + "\\%")
    wr("fig_ttl.tex", r"""\begin{figure}[t]
\centering
\begin{tikzpicture}
\begin{axis}[width=\columnwidth, height=4.6cm, xmin=-3, xmax=103, ymin=-3, ymax=103,
  xlabel={Refreshed fact uses (\%)}, ylabel={Missed changes (\%)}, label style={font=\small}, ticklabel style={font=\scriptsize},
  legend style={font=\scriptsize, at={(0.99,0.99)}, anchor=north east, draw=none, fill=white, fill opacity=0.85, text opacity=1, legend columns=2}]
\addplot[gray,thick,dashed,mark=x] coordinates {""" + ttl_pts + r"""};
\addlegendentry{TTL 5--300\,s}
""" + "\n".join(pts) + r"""
\end{axis}
\end{tikzpicture}
\caption{Work vs.\ staleness, all gaps pooled (late decision). A fixed TTL ignores whether anything changed, so it moves along the diagonal: every refresh it saves is a change it misses. \sys is the only policy with zero misses below 100\% refresh.}
\label{fig:ttl}
\end{figure}
""")


