def tab_persource():
    rows = rd("e2_per_source.csv")
    if not rows:
        return
    lines = []
    for r in rows:
        u, ch, un = int(r["uses"]), int(r["changed"]), int(r["unchanged"])
        name = SRCNAME.get(r["source"], "Derived")
        if r["source"] == "derived":
            unk = "--"; fr = pct(int(r["fresh"]) / u, 0); fal = "--"; sav = pct(int(r["unch_fresh"]) / max(1, un), 0)
        else:
            unk = pct(int(r["unknown"]) / u, 0); fr = pct(int(r["fresh"]) / u, 0)
            fal = pct(int(r["unch_false_inval"]) / max(1, un), 0); sav = pct(int(r["unch_fresh"]) / max(1, un), 0)
        lines.append("%s & %d & %s & %s & %s & %s & %s & %s/%d & %s/%d \\\\" % (name, u, pct(ch / u, 0), fr, unk, sav, fal,
                     r["chg_detected"], ch, r["ev_miss"], ch))
    wr("tab_persource.tex", r"""\begin{table}[t]
\centering
\caption{\sys per source, late decisions over all gaps. Fresh/Unknown: share of uses. Reused: unchanged uses served from memory. False inval.: unchanged uses marked \Changed. Detected: changed uses refreshed by \sys, vs.\ missed by event-only.}
\label{tab:persource}
\scriptsize
\setlength{\tabcolsep}{2.2pt}
\begin{tabular}{@{}lrrrrrrrr@{}}
\toprule
Source & Uses & Chg.\,\% & Fresh\,\% & Unkn.\,\% & Reused\,\% & False\,inval.\,\% & \sys detected & Ev.\ missed \\
\midrule
""" + "\n".join(lines) + r"""
\bottomrule
\end{tabular}
\end{table}
""")


