#!/usr/bin/env python3
"""artifact/results/derived/*.csv + summary.json -> manuscript/generated/{macros.tex, tab_*.tex, fig_*.tex}.

Every number in the paper's tables, plots and results prose is produced here. Do not edit generated files.
"""
import csv
import json
import math
import os

HERE = os.path.dirname(os.path.abspath(__file__))
DER = os.path.join(HERE, "..", "results", "derived")
OUT = os.path.join(HERE, "..", "..", "manuscript", "generated")
os.makedirs(OUT, exist_ok=True)

GAPNAME = {"none": "No gap (background)", "freeze": "Cached-app freezer", "doze": "Doze + restricted bucket",
           "unregister": "Observer unregistered", "kill": "Process killed (\\texttt{am kill})",
           "forcestop": "Force-stop", "perm": "Permission revoked", "reboot": "Reboot"}
GAPSHORT = {"none": "none", "freeze": "freeze", "doze": "doze", "unregister": "unreg.", "kill": "kill",
            "forcestop": "f-stop", "perm": "perm.", "reboot": "reboot"}
GAPS = ["none", "freeze", "doze", "unregister", "kill", "forcestop", "perm", "reboot"]
POLNAME = {"ev": "Event-only", "te": "Tether-style", "trig": "+OS trigger", "lme": "\\sys-epoch", "lm": "\\sys", "gl": "Global"}
SRCNAME = {"contacts": "Contacts", "sms": "SMS", "calllog": "Call log", "media": "MediaStore", "calendar": "Calendar",
           "settings": "Settings", "files": "Shared files"}
MACROS = []


def rd(name):
    p = os.path.join(DER, name)
    if not os.path.exists(p):
        return []
    with open(p, newline="") as f:
        return list(csv.DictReader(f))


def S():
    p = os.path.join(DER, "summary.json")
    return json.load(open(p)) if os.path.exists(p) else {}


def wr(name, text):
    with open(os.path.join(OUT, name), "w") as f:
        f.write("% AUTO-GENERATED by artifact/scripts/render.py -- do not edit\n" + text)


def mac(name, val):
    MACROS.append("\\newcommand{\\%s}{%s\\xspace}" % (name, val))


def f(x, nd=1):
    try:
        x = float(x)
    except (TypeError, ValueError):
        return "--"
    if math.isnan(x):
        return "--"
    return ("%." + str(nd) + "f") % x


def pct(x, nd=1):
    try:
        x = float(x)
    except (TypeError, ValueError):
        return "--"
    if math.isnan(x):
        return "--"
    return ("%." + str(nd) + "f") % (100 * x)


# ------------------------------------------------------------------ coverage table
def tab_coverage():
    rows = rd("e1_candidates.csv")
    ad = {r["source"]: r for r in rd("e1_adapters.csv")}
    if not rows:
        return
    def cell(r, k):
        if not r.get(k + "_n"):
            return "--"
        kk, n, down = int(r[k + "_k"]), int(r[k + "_n"]), int(r[k + "_down"] or 0)
        s = "%d/%d" % (kk, n)
        if down:
            s += "$^{\\downarrow}$"
        return s
    lines = []
    last = None
    for r in rows:
        src = SRCNAME[r["source"]] if r["source"] != last else ""
        if r["source"] != last and last is not None:
            lines.append("\\addlinespace[1pt]")
        last = r["source"]
        lines.append("%s & %s & %s & %s & %s & %s \\\\" % (src, r["label"], cell(r, "insert"), cell(r, "update"), cell(r, "delete"), cell(r, "none")))
    lines.append("\\midrule")
    names = {"contacts": "TS + tombstone", "calllog": "\\texttt{LAST\\_MODIFIED}${}^{\\dagger}$",
             "media": "generation${}^{\\dagger}$", "files": "mtime, racy guard"}
    for s in ["contacts", "calllog", "media", "files"]:
        a = ad.get(s)
        if not a:
            continue
        c = lambda k: "%s/%s" % (a[k + "_k"], a[k + "_n"])
        lines.append("%s & \\sys: %s & %s & %s & %s & %s \\\\" % (SRCNAME[s], names[s], c("insert"), c("update"), c("delete"), c("none")))
    lines.append("\\multicolumn{2}{@{}l}{SMS, calendar events, Settings: none} & \\multicolumn{4}{c}{$\\Rightarrow$ \\Unknown} \\\\")
    body = "\n".join(lines)
    wr("tab_coverage.tex", r"""\begin{table}[t]
\centering
\caption{Durable change evidence (E1): trials in which a candidate moved after one injected mutation of each kind; ``none'' = source untouched. $\downarrow$: moved downward in some trials (not monotone). $\dagger$: deletions of tracked rows are caught by the support check.}
\label{tab:coverage}
\scriptsize
\setlength{\tabcolsep}{2.4pt}
\begin{tabular}{@{}llrrrr@{}}
\toprule
Source & Candidate evidence & Insert & Update & Delete & None \\
\midrule
""" + body + r"""
\bottomrule
\end{tabular}
\end{table}
""")


