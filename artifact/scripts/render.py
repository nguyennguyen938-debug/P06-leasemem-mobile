def rd(name):
    p = os.path.join(DER, name)
    if not os.path.exists(p):
        return []
    with open(p, newline="") as f:
        return list(csv.DictReader(f))


def S():
    p = os.path.join(DER, "summary.json")
    return json.load(open(p)) if os.path.exists(p) else {}


def wr(name, text):
    with open(os.path.join(OUT, name), "w", newline="") as f:
        f.write("% AUTO-GENERATED by artifact/scripts/render.py; do not edit\n" + text)


def mac(name, val):
    MACROS.append("\\newcommand{\\%s}{%s\\xspace}" % (name, val))


def f(x, nd=1):
    try:
        x = float(x)
    except (TypeError, ValueError):
        return NA
    return NA if math.isnan(x) else ("%." + str(nd) + "f") % x


def pct(x, nd=0):
    try:
        x = float(x)
    except (TypeError, ValueError):
        return NA
    return NA if math.isnan(x) else ("%." + str(nd) + "f") % (100 * x)


def gkey(g):
    return ORDER.index(g) if g in ORDER else 99


GROUP_RE = re.compile(r"^(\\addlinespace\[\d+pt\]|\\midrule)?\\multicolumn\{(\d+)\}\{@\{\}l\}\{\\emph\{(.*)\}\}\\\\$")


def mstyle(header, lines):
    """Matured table look (manuscript/matured-style.tex): shaded header rows and shaded group rows."""
    header = "\\mhead " + header.replace(" \\\\ ", " \\\\ \\mhead ")
    out = []
    for l in lines:
        m = GROUP_RE.match(l)
        out.append(("\\midrule\n" if m.group(1) == "\\midrule" else "") + "\\mgroup{%s}{%s}" % (m.group(2), m.group(3)) if m else l)
    return header, out


def bad(v):
    """Tint a nonzero missed-change cell."""
    return v if v in ("0", NA) else "\\mbad{%s}" % v


def stk(*parts):
    """Two-line right-aligned header cell."""
    return "\\begin{tabular}[b]{@{}r@{}}%s\\end{tabular}" % "\\\\".join(parts)


def table(name, label, caption, colspec, header, lines, star=False, size="\\footnotesize", where="t", sep=None):
    star = star or name in {"tab_aw.tex", "tab_fgcost.tex", "tab_host.tex", "tab_persource.tex", "tab_sig.tex"}
    env = "table*" if star else "table"
    size = {"\\footnotesize": "\\mtab", "\\scriptsize": "\\mtab\\scriptsize"}.get(size, size)
    header, lines = mstyle(header, lines)
    colspec = re.sub(r"^@\{\}|@\{\}$", "", colspec)   # shaded rows need the outer padding
    lines = [l.replace("{@{}l}", "{l}") for l in lines]
    sepl = "\\setlength{\\tabcolsep}{%s}\n" % sep if sep else ""
    wr(name, "\\begin{%s}[%s]\n\\centering\n\\caption{%s}\n\\label{%s}\n%s\n%s\\begin{tabular}{%s}\n\\toprule\n%s \\\\\n\\midrule\n%s\n\\bottomrule\n\\end{tabular}\n\\end{%s}\n"
       % (env, where, caption, label, size, sepl, colspec, header, "\n".join(lines), env))


# ================================================================== E1 coverage (main + all candidates + API 35)
def coverage():
    rows = rd("e1_candidates.csv")
    if not rows:
        return
    S_ = S()
    def cell(r, k):
        if not r.get(k + "_n"):
            return NA
        if int(r.get(k + "_err") or 0) == int(r[k + "_n"]):
            return "ERR"
        s = "%s/%s" % (r[k + "_k"], r[k + "_n"])
        return s + ("$^{\\downarrow}$" if int(r.get(k + "_down") or 0) else "")
    main = [r for r in rows if r["tag"] == "e1" and r["main"] == "1"]
    lines, last = [], None
    for r in main:
        if last is not None and r["source"] != last:
            lines.append("\\addlinespace[1pt]")
        src = SRCNAME[r["source"]] if r["source"] != last else ""
        last = r["source"]
        lines.append("%s & %s & %s & %s & %s & %s \\\\" % (src, r["label"], cell(r, "insert"), cell(r, "update"), cell(r, "delete"), cell(r, "none")))
    va = S_.get("ver_adapter", {})
    lines.append("\\midrule")
    lines.append("\\multicolumn{2}{@{}l}{\\stamp Contacts adapter (VERSION map)} & %s & %s & %s & %s \\\\" % tuple(va.get(k, NA) for k in ("insert", "update", "delete", "none")))
    lines.append("\\multicolumn{2}{@{}l}{SMS, calendar events, Settings: none found} & \\multicolumn{4}{c}{$\\Rightarrow$ \\Unknown} \\\\")
    table("tab_coverage.tex", "tab:coverage",
          "Durable change evidence on Android~13: trials in which a candidate moved after one mutation of each kind by another app; ``None'' = source untouched. $\\downarrow$: moved downward in some trials. All probed candidates and the Android~15 replication are in Table~\\ref{tab:allcands}.",
          "@{}llrrrr@{}", "Source & Candidate & Insert & Update & Delete & None", lines, size="\\scriptsize", sep="2.4pt")
    # all candidates, API 33 vs API 35
    lines = []
    for r in [x for x in rows if x["tag"] == "e1"]:
        r35 = next((x for x in rows if x["tag"] == "e1api35" and x["key"] == r["key"]), None)
        c35 = " / ".join(cell(r35, k) for k in ("insert", "update", "delete", "none")) if r35 else NA
        lines.append("%s & %s & %s & %s \\\\" % (SRCNAME[r["source"]], r["label"], " / ".join(cell(r, k) for k in ("insert", "update", "delete", "none")), c35))
    table("tab_allcands.tex", "tab:allcands", "Every candidate probed in the source campaign (insert / update / delete / none). API~33: %s trials; API~35: %s trials." % (S_.get("e1_trials", NA), S_.get("e1api35_trials", NA)),
          "@{}llll@{}", "Source & Candidate & API 33 & API 35", lines, star=True, size="\\scriptsize", where="!ht")


# ================================================================== latency table
def latency():
    S_ = S()
    rows = [("Android 13, background", "e1", "bg"), ("Android 13, foreground", "e1", "fg"), ("Android 15, background$^{*}$", "e1api35", "bg")]
    lines = []
    for name, tag, mode in rows:
        k = "%s_prov_%s_med_ms" % (tag, mode)
        if S_.get(k) is None:
            continue
        files = S_.get("%s_files_bg_med_ms" % tag) if mode == "bg" else None
        lines.append("%s & %s & %s & %s \\\\" % (name, f(S_[k] / 1000.0, 1) + "\\,s" if S_[k] >= 1000 else f(S_[k], 1) + "\\,ms",
                                                (f(S_.get("%s_prov_bg_p5_ms" % tag) / 1000.0, 1) + "\\,s") if mode == "bg" and S_.get("%s_prov_bg_p5_ms" % tag) else NA,
                                                (f(files, 0) + "\\,ms") if files is not None else NA))
    table("tab_latency.tex", "tab:latency",
          "Delay from a mutation to the first \\texttt{ContentObserver} callback in a live client; FileObserver = inotify. $^{*}$Mixed freezer state.",
          "@{}lrrr@{}", "Client & " + stk("Provider", "median") + " & " + stk("Provider", "5th pct.") + " & " + stk("FileObserver", "median"), lines, size="\\footnotesize", sep="3pt")
    for tag in ("e1", "e1api35"):
        T = "A" if tag == "e1" else "B"
        if S_.get("%s_prov_bg_med_ms" % tag):
            mac("ProvLat%s" % T, f(S_["%s_prov_bg_med_ms" % tag] / 1000.0, 1))
            mac("ProvMin%s" % T, f(S_["%s_prov_bg_min_ms" % tag] / 1000.0, 2))
            mac("ProvN%s" % T, S_["%s_prov_bg_n" % tag])
            mac("ProvBelow%s" % T, S_.get("%s_prov_bg_below10s" % tag, NA))
            mac("ProvPfive%s" % T, f(S_["%s_prov_bg_p5_ms" % tag] / 1000.0, 1))
    mac("FgLatMs", f(S_.get("e1_prov_fg_med_ms"), 1))
    mac("FileLatMs", f(S_.get("e1_files_bg_med_ms"), 0))
    mac("LatDropped", S_.get("e1_lat_dropped", NA))
    mac("EOneTrials", S_.get("e1_trials", NA))
    mac("EOneFgTrials", S_.get("e1_fg_trials", NA))
    mac("EOneBgTrials", (S_.get("e1_trials", 0) or 0) - (S_.get("e1_fg_trials", 0) or 0))
    mac("EOneApiTrials", S_.get("e1api35_trials", NA))


# ================================================================== gap taxonomy
REASON = {"2": "SIGNALED", "3": "LOW\\_MEMORY", "8": "PERMISSION\\_CHANGE", "10": "USER\\_REQUESTED", "13": "OTHER", "0": "UNKNOWN"}


def sec(x):
    """Seconds in one unit: one decimal from 1 s, three below it (no ms/s mix in a column)."""
    return f(x, 1 if float(x) >= 1 else 3)


def taxonomy():
    rows = rd("e2_taxonomy.csv")
    if not rows:
        return
    lines = []
    groups = [("api33", "v3", "bg", "Android 13, background client"), ("api33", "v3", "fg", "Android 13, foreground-service client"),
              ("api35", "v3", "bg", "Android 15, background client; mixed freezer state")]
    for plat, proto, client, title in groups:
        R = sorted([r for r in rows if (r["platform"], r["protocol"], r["client"]) == (plat, proto, client)], key=lambda r: gkey(r["gap"]))
        if not R:
            continue
        lines.append("\\addlinespace[2pt]\\multicolumn{8}{@{}l}{\\emph{%s}}\\\\" % title)
        for r in R:
            n, ns = int(r["n"]), max(1, int(r["n_src_changed"]))
            rs = ", ".join(REASON.get(x.split(":")[0], x.split(":")[0]) for x in r["exit_reasons"].split(";") if x)
            fcl = ("%s / %s" % (sec(r["fcl_med_s"]), sec(r["fcl_max_s"]))) if r["fcl_med_s"] else "none"
            lines.append("%s & %d & %s & %s & %s & %s & %s & %s \\\\" % (GAPNAME.get(r["gap"], r["gap"]), n, pct(int(r["survived"]) / n), fcl,
                         pct(int(r["ev_early"]) / ns), pct(int(r["ev_late"]) / ns), pct(int(r["trig"]) / ns),
                         "%s/%d%s" % (r["exit_new"], n, (" {\\scriptsize %s}" % rs) if rs else "")))
            tag = ("" if (plat, client) == ("api33", "bg") else ("Fg" if client == "fg" else "Api"))
            G = r["gap"].capitalize().replace("2", "Two")
            mac("Surv%s%s" % (tag, G), pct(int(r["survived"]) / n) + "\\%")
            mac("EvEarly%s%s" % (tag, G), pct(int(r["ev_early"]) / ns) + "\\%")
            mac("EvLate%s%s" % (tag, G), pct(int(r["ev_late"]) / ns) + "\\%")
            mac("Trig%s%s" % (tag, G), pct(int(r["trig"]) / ns) + "\\%")
            mac("N%s%s" % (tag, G), str(n))
            mac("Hold%s%s" % (tag, G), f(r["hold_med"], 0))
            if r["fcl_med_s"]:
                mac("Fcl%s%s" % (tag, G), sec(r["fcl_med_s"])); mac("FclMax%s%s" % (tag, G), sec(r["fcl_max_s"]))
            if r.get("doze_idle_at_batch2"):
                mac("DozeIdleTwo%s%s" % (tag, G), r["doze_idle_at_batch2"])
                mac("DozeMaintTwo%s%s" % (tag, G), n - int(r["doze_idle_at_batch2"]))   # trials not in deep idle at batch 2
    table("tab_gaps.tex", "tab:gaps",
          "What each gap does to a live or restarted client. First callback: median / max delay from a provider mutation to its first \\texttt{ContentObserver} callback. Notified: share of changed provider sources with a callback by the early (+2\\,s) and late (+14\\,s) decision. Trigger: the JobScheduler content trigger (its own package, same gap) fired. Exit: new \\texttt{ApplicationExitInfo} records.",
          "@{}lrrrrrrl@{}", "Gap & Trials & Survived\\,\\% & First callback (s) & Notified early\\,\\% & Notified late\\,\\% & Trigger\\,\\% & Exit record", lines, star=True, size="\\scriptsize")


